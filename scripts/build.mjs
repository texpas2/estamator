#!/usr/bin/env node
/** Builds dist/catalog.json (one merged document) and dist/seed.sql (idempotent inserts). */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadCatalog, resolveZip3, regionFactorRows, metroSlug } from './lib/load.mjs';

const { units, laborRates, trades, pricingProfiles, workItems, packages, regions } = loadCatalog();
const zip3Rows = resolveZip3(regions);
const regionRows = regionFactorRows(regions);

const dist = join(ROOT, 'dist');
mkdirSync(dist, { recursive: true });

// --- dist/catalog.json ------------------------------------------------------
const catalog = {
  generated_at: new Date().toISOString().slice(0, 10),
  basis: { currency: 'USD', market: 'US national average (index 100)', labor_rates: laborRates.basis },
  units,
  labor_rates: laborRates.rates,
  pricing_profiles: pricingProfiles,
  trades: trades.map((t) => ({
    slug: t.slug, code: t.code, name: t.name, sort: t.sort,
    sections: t.sections.map((s) => ({
      slug: s.slug, name: s.name,
      items: workItems
        .filter((w) => w.trade === t.slug && w.section === s.slug)
        .map(({ sourceFile, trade, section, ...rest }) => rest),
    })),
  })),
  regions: {
    basis: regions.states.basis,
    factors: regionRows,
    zip3: zip3Rows.map((r) => ({ zip3: r.zip3, state: r.state, region: r.regionCode, name: r.regionName,
                                 labor: r.labor, material: r.material, equipment: r.equipment, composite: r.composite })),
  },
  packages: packages.map(({ sourceFile, ...p }) => p),
};
writeFileSync(join(dist, 'catalog.json'), JSON.stringify(catalog, null, 2) + '\n');

// --- dist/seed.sql ----------------------------------------------------------
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'NULL' : String(v));
const b = (v) => (v ? 'true' : 'false');

const out = [];
out.push('-- Generated by scripts/build.mjs — do not edit. Run db/schema.sql first.');
out.push(`-- ${catalog.generated_at}: ${workItems.length} work items, ${packages.length} packages, ${zip3Rows.length} ZIP3 rows.`);
out.push('BEGIN;', '');

out.push('-- units');
for (const u of units)
  out.push(`INSERT INTO unit (code,name,system,base,to_base) VALUES (${q(u.code)},${q(u.name)},${q(u.system)},${q(u.base)},${n(u.to_base)}) ON CONFLICT (code) DO UPDATE SET name=EXCLUDED.name,system=EXCLUDED.system,base=EXCLUDED.base,to_base=EXCLUDED.to_base;`);

out.push('', '-- labor rates');
for (const r of laborRates.rates)
  out.push(`INSERT INTO labor_rate (key,name,usd_per_hour) VALUES (${q(r.key)},${q(r.name)},${n(r.usd_per_hour)}) ON CONFLICT (key) DO UPDATE SET name=EXCLUDED.name,usd_per_hour=EXCLUDED.usd_per_hour;`);

out.push('', '-- pricing profiles');
for (const p of pricingProfiles)
  out.push(`INSERT INTO pricing_profile (slug,name,description,overhead_pct,profit_pct,contingency_pct,material_sales_tax_pct,permit_fee_pct,is_default) VALUES (${q(p.slug)},${q(p.name)},${q(p.description)},${n(p.overhead_pct)},${n(p.profit_pct)},${n(p.contingency_pct)},${n(p.material_sales_tax_pct)},${n(p.permit_fee_pct)},${b(p.is_default)}) ON CONFLICT (slug) DO UPDATE SET name=EXCLUDED.name,description=EXCLUDED.description,overhead_pct=EXCLUDED.overhead_pct,profit_pct=EXCLUDED.profit_pct,contingency_pct=EXCLUDED.contingency_pct,material_sales_tax_pct=EXCLUDED.material_sales_tax_pct,permit_fee_pct=EXCLUDED.permit_fee_pct,is_default=EXCLUDED.is_default;`);

out.push('', '-- trades and sections');
for (const t of trades) {
  out.push(`INSERT INTO trade (slug,code,name,sort_order) VALUES (${q(t.slug)},${q(t.code)},${q(t.name)},${n(t.sort)}) ON CONFLICT (slug) DO UPDATE SET code=EXCLUDED.code,name=EXCLUDED.name,sort_order=EXCLUDED.sort_order;`);
  t.sections.forEach((s, i) =>
    out.push(`INSERT INTO section (trade_id,slug,name,sort_order) SELECT id,${q(s.slug)},${q(s.name)},${n((i + 1) * 10)} FROM trade WHERE slug=${q(t.slug)} ON CONFLICT (trade_id,slug) DO UPDATE SET name=EXCLUDED.name,sort_order=EXCLUDED.sort_order;`));
}

out.push('', '-- work items');
for (const w of workItems) {
  out.push(
    `INSERT INTO work_item (code,slug,section_id,name,unit_code,labor_hours_per_unit,crew_size,labor_rate_key,` +
    `material_cost_per_unit,waste_factor_pct,min_charge,permit_required,notes) SELECT ${q(w.code)},${q(w.slug)},s.id,` +
    `${q(w.name)},${q(w.unit)},${n(w.labor_hours_per_unit)},${n(w.crew_size)},${q(w.labor_rate_key)},` +
    `${n(w.material_cost_per_unit_usd)},${n(w.waste_factor_pct)},${n(w.min_charge_usd)},${b(w.permit)},${q(w.notes)} ` +
    `FROM section s JOIN trade t ON t.id=s.trade_id WHERE t.slug=${q(w.trade)} AND s.slug=${q(w.section)} ` +
    `ON CONFLICT (code) DO UPDATE SET slug=EXCLUDED.slug,section_id=EXCLUDED.section_id,name=EXCLUDED.name,` +
    `unit_code=EXCLUDED.unit_code,labor_hours_per_unit=EXCLUDED.labor_hours_per_unit,crew_size=EXCLUDED.crew_size,` +
    `labor_rate_key=EXCLUDED.labor_rate_key,material_cost_per_unit=EXCLUDED.material_cost_per_unit,` +
    `waste_factor_pct=EXCLUDED.waste_factor_pct,min_charge=EXCLUDED.min_charge,permit_required=EXCLUDED.permit_required,notes=EXCLUDED.notes;`);
  for (const tag of w.tags ?? [])
    out.push(`INSERT INTO work_item_tag (work_item_id,tag) SELECT id,${q(tag)} FROM work_item WHERE code=${q(w.code)} ON CONFLICT DO NOTHING;`);
}

out.push('', '-- region factors');
for (const r of regionRows)
  out.push(`INSERT INTO region_factor (level,code,name,state,labor_index,material_index,equipment_index,composite_index) VALUES (${q(r.level)},${q(r.code)},${q(r.name)},${q(r.state)},${n(r.labor)},${n(r.material)},${n(r.equipment)},${n(r.composite)}) ON CONFLICT (level,code) DO UPDATE SET name=EXCLUDED.name,state=EXCLUDED.state,labor_index=EXCLUDED.labor_index,material_index=EXCLUDED.material_index,equipment_index=EXCLUDED.equipment_index,composite_index=EXCLUDED.composite_index;`);

out.push('', `-- zip3 lookup (${zip3Rows.length} assigned prefixes)`);
for (const z of zip3Rows)
  out.push(`INSERT INTO zip3_region (zip3,state,region_factor_id,metro_name) SELECT ${q(z.zip3)},${q(z.state)},id,${z.level === 'metro' ? q(z.regionName) : 'NULL'} FROM region_factor WHERE level=${q(z.level)} AND code=${q(z.regionCode)} ON CONFLICT (zip3) DO UPDATE SET state=EXCLUDED.state,region_factor_id=EXCLUDED.region_factor_id,metro_name=EXCLUDED.metro_name;`);

out.push('', '-- packages');
for (const p of packages) {
  out.push(`INSERT INTO package (slug,name,category,tier,description) VALUES (${q(p.slug)},${q(p.name)},${q(p.category)},${q(p.tier)},${q(p.description)}) ON CONFLICT (slug) DO UPDATE SET name=EXCLUDED.name,category=EXCLUDED.category,tier=EXCLUDED.tier,description=EXCLUDED.description;`);
  (p.variables ?? []).forEach((v, i) =>
    out.push(`INSERT INTO package_variable (package_id,key,name,unit_code,default_value,sort_order) SELECT id,${q(v.key)},${q(v.name)},${v.unit && units.some((u) => u.code === v.unit) ? q(v.unit) : 'NULL'},${n(v.default)},${n((i + 1) * 10)} FROM package WHERE slug=${q(p.slug)} ON CONFLICT (package_id,key) DO UPDATE SET name=EXCLUDED.name,unit_code=EXCLUDED.unit_code,default_value=EXCLUDED.default_value,sort_order=EXCLUDED.sort_order;`));
  p.items.forEach((it, i) =>
    out.push(`INSERT INTO package_item (package_id,work_item_id,qty_formula,is_optional,note,sort_order) SELECT p.id,w.id,${q(it.qty)},${b(it.optional)},${q(it.note)},${n((i + 1) * 10)} FROM package p, work_item w WHERE p.slug=${q(p.slug)} AND w.code=${q(it.code)} ON CONFLICT (package_id,work_item_id) DO UPDATE SET qty_formula=EXCLUDED.qty_formula,is_optional=EXCLUDED.is_optional,note=EXCLUDED.note,sort_order=EXCLUDED.sort_order;`));
}

out.push('', 'COMMIT;', '');
writeFileSync(join(dist, 'seed.sql'), out.join('\n'));

console.log(`dist/catalog.json  ${workItems.length} work items, ${packages.length} packages`);
console.log(`dist/seed.sql      ${out.length} statements incl. ${zip3Rows.length} ZIP3 rows`);
